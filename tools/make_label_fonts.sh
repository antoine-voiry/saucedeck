#!/bin/sh
# Rebuild include/fonts/FreeSans7pt7b.h (icon tile labels, Plan 5). Regular only: bold 7pt
# comes out with dotless i/j (docs/kb/toolchain.md).
# Source: GNU FreeFont 20120503 TTFs, converted by Adafruit GFX fontconvert (DPI 141) from the
# library PlatformIO already fetched (.pio/libdeps/saucedeck, run `pio run -e saucedeck` once).
# Needs: curl, shasum, cc, FreeType (brew install freetype pkg-config). Work files go to a temp dir.
set -eu

ROOT=$(cd "$(dirname "$0")/.." && pwd)
URL=https://ftp.gnu.org/gnu/freefont/freefont-ttf-20120503.zip
SHA256=7c85baf1bf82a1a1845d1322112bc6ca982221b484e3b3925022e25b5cae89af
GFX="$ROOT/.pio/libdeps/saucedeck/Adafruit GFX Library"
OUT="$ROOT/include/fonts"
SIZE=7

[ -f "$GFX/fontconvert/fontconvert.c" ] || { echo "missing $GFX: run pio run -e saucedeck first" >&2; exit 1; }
GFX_VER=$(sed -n 's/^version=//p' "$GFX/library.properties")

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

curl -fsSL -o "$WORK/freefont.zip" "$URL"
echo "$SHA256  $WORK/freefont.zip" | shasum -a 256 -c - >/dev/null || { echo "sha256 mismatch" >&2; exit 1; }
unzip -q "$WORK/freefont.zip" -d "$WORK"
TTF="$WORK/freefont-20120503"

# fontconvert.c includes "../gfxfont.h": build it next to a copy of the header.
cp "$GFX/fontconvert/fontconvert.c" "$GFX/gfxfont.h" "$WORK/"
sed -i.bak 's|"../gfxfont.h"|"gfxfont.h"|' "$WORK/fontconvert.c"
# shellcheck disable=SC2046
cc -O2 -w -o "$WORK/fontconvert" "$WORK/fontconvert.c" $(pkg-config --cflags --libs freetype2)

mkdir -p "$OUT"
for face in FreeSans; do
  name="${face}${SIZE}pt7b"
  {
    echo "// $name: GNU FreeFont 20120503 $face.ttf ($URL, sha256 $SHA256),"
    echo "// converted at ${SIZE} pt / DPI 141 by Adafruit GFX $GFX_VER fontconvert. Generated by"
    echo "// tools/make_label_fonts.sh, do not edit. Licence: GNU FreeFont, GPLv3 with font exception"
    echo "// (embedding the font in a document/firmware does not by itself make it GPL)."
    echo "#pragma once"
    echo "#include <Adafruit_GFX.h>"
    echo
    "$WORK/fontconvert" "$TTF/$face.ttf" "$SIZE"
  } >"$OUT/$name.h"
  echo "wrote $OUT/$name.h"
done
